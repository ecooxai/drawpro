import asyncio
from painting_ui import Painter

async def patches(p,color,items):
    await p.color(color); await p.size(2); await p.tool('brush')
    for points,seed in items: await p.drag(points+[points[0]])
    await p.tool('fill')
    for points,seed in items: await p.click(*seed)
    await p.tool('brush')

